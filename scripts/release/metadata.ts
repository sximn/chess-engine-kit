import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { root } from "../lib.ts";

export const registry = "https://registry.npmjs.org";
export type Channel = "next" | "latest";

export function releaseNotes(markdown: string, version: string): string {
  const sections = [...markdown.matchAll(/^## \[([^\]]+)\](.*)$/gm)];
  const matches = sections.filter((section) => section[1] === version);
  if (matches.length !== 1) {
    throw Error(
      `CHANGELOG.md must contain exactly one ## [${version}] - YYYY-MM-DD entry. Move the release notes out of Unreleased before tagging.`,
    );
  }
  const section = matches[0];
  const date = /^ - (\d{4}-\d{2}-\d{2})\s*$/.exec(section[2])?.[1];
  if (
    !date ||
    Number.isNaN(Date.parse(date)) ||
    new Date(date).toISOString().slice(0, 10) !== date
  ) {
    throw Error("The changelog release heading needs a valid YYYY-MM-DD date.");
  }
  const next = sections[sections.indexOf(section) + 1];
  const notes = markdown
    .slice(section.index! + section[0].length, next?.index)
    .trim();
  if (!/^- \S/m.test(notes) || /\b(TODO|TBD|PLACEHOLDER)\b/i.test(notes)) {
    throw Error(
      "The changelog release entry needs real bullet-point release notes, without TODO/TBD placeholders.",
    );
  }
  return notes + "\n";
}

export function git(args: string[], cwd = root): string {
  return execFileSync("git", args, {
    cwd,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  }).trimEnd();
}

export function validateRelease(tag: string, channel: string, cwd = root) {
  const pkg = JSON.parse(
    fs.readFileSync(path.join(cwd, "package.json"), "utf8"),
  );
  const number = "(0|[1-9][0-9]*)";
  const semver = new RegExp(
    `^${number}\\.${number}\\.${number}(?:-([0-9A-Za-z-]+(?:\\.[0-9A-Za-z-]+)*))?$`,
  );
  const match = semver.exec(pkg.version);
  if (
    !match ||
    match[4]?.split(".").some((part: string) => /^0[0-9]+$/.test(part))
  ) {
    throw Error(
      "package.json needs a canonical SemVer version (optionally with a prerelease, without build metadata).",
    );
  }
  if (tag !== `v${pkg.version}`)
    throw Error(`Release tag must be v${pkg.version}, matching package.json.`);
  if (channel !== "next" && channel !== "latest")
    throw Error("Choose the next or latest npm channel.");
  if (match[4] && channel === "latest")
    throw Error("Prerelease versions must use the next channel.");
  const expectedRepository = process.env.GITHUB_REPOSITORY;
  const repository = pkg.repository?.url
    ?.replace(/^git\+/, "")
    .replace(/\.git$/, "");
  if (
    !/^https:\/\/github\.com\/[^/]+\/[^/]+$/.test(repository ?? "") ||
    repository.includes("REPLACE_ME") ||
    (expectedRepository &&
      repository !== `https://github.com/${expectedRepository}`)
  ) {
    throw Error(
      "package.json repository.url must match the publishing GitHub repository.",
    );
  }
  const notes = releaseNotes(
    fs.readFileSync(path.join(cwd, "CHANGELOG.md"), "utf8"),
    pkg.version,
  );
  // This tracked file is generated by SDK builds and is excluded from the input fingerprint.
  const dirty = git(["status", "--porcelain", "--untracked-files=all"], cwd)
    .split("\n")
    .filter(
      (line) => line && line !== " M src/adapters/frozenight/manifest.ts",
    );
  if (dirty.length)
    throw Error(
      "Release inputs must be committed and the checkout clean before publishing.\n" +
        dirty.join("\n"),
    );
  const commit = git(["rev-parse", "HEAD"], cwd);
  if (
    process.env.RELEASE_EXPECTED_COMMIT &&
    commit !== process.env.RELEASE_EXPECTED_COMMIT
  ) {
    throw Error(
      "Checked-out source does not match the workflow commit; refusing incorrect provenance.",
    );
  }
  let taggedCommit: string;
  try {
    taggedCommit = git(
      ["rev-parse", "--verify", `refs/tags/${tag}^{commit}`],
      cwd,
    );
  } catch {
    throw Error(
      `Create and push the ${tag} Git tag before running the release workflow.`,
    );
  }
  if (taggedCommit !== commit)
    throw Error(`Check out ${tag}; its commit does not match HEAD.`);
  const branch = process.env.RELEASE_DEFAULT_BRANCH;
  if (branch) {
    try {
      git(
        [
          "merge-base",
          "--is-ancestor",
          commit,
          `refs/remotes/origin/${branch}`,
        ],
        cwd,
      );
    } catch {
      throw Error(
        `Release tags must point to commits on the default branch (${branch}).`,
      );
    }
  }
  return {
    name: pkg.name as string,
    version: pkg.version as string,
    commit,
    tag,
    channel: channel as Channel,
    notes,
  };
}

export function releaseArguments(args: string[]) {
  let tag = "",
    channel = "next";
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--tag" && args[i + 1]) tag = args[++i];
    else if (args[i] === "--channel" && args[i + 1]) channel = args[++i];
    else throw Error("Use --tag v<version> --channel next|latest.");
  }
  return { tag, channel };
}
